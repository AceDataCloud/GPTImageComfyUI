"""Refresh public model/quality contracts without changing the saved node layout."""

import argparse
import json
from datetime import date
from pathlib import Path
from pprint import pformat
from urllib.request import urlopen

ROOT = Path(__file__).resolve().parents[1]
CONTRACT = ROOT / "contracts/images.json"
TARGET = ROOT / "image_contracts.py"


def generate(contracts):
    values = {}
    for operation, contract in contracts.items():
        values[operation] = {}
        for field, schema in contract["fields"].items():
            enum = schema["enum"]
            if not enum or len(enum) != len(set(enum)) or not all(isinstance(v, str) and v for v in enum):
                raise ValueError(f"Invalid {operation} {field} enum")
            values[operation][field] = enum
    return ('"""Generated by scripts/sync_image_contracts.py; edit contracts/images.json."""\n\n'
            + "IMAGE_CHOICES = " + pformat(values, sort_dicts=False, width=95) + "\n")


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    group = parser.add_mutually_exclusive_group()
    group.add_argument("--refresh", action="store_true", help="Read the public API contract; never submit an image request")
    group.add_argument("--check", action="store_true", help="Offline reproducibility check")
    args = parser.parse_args()
    contracts = json.loads(CONTRACT.read_text())
    if args.refresh:
        for contract in contracts.values():
            with urlopen(contract["source"], timeout=30) as response:
                api = json.load(response)
            schema = api["definition"]["paths"][contract["path"]]["post"]["requestBody"]["content"]["application/json"]["schema"]
            contract["captured_at"] = date.today().isoformat()
            contract["fields"] = {name: {"enum": schema["properties"][name]["enum"], "type": "string"} for name in contract["fields"]}
        CONTRACT.write_text(json.dumps(contracts, indent=2) + "\n")
    content = generate(contracts)
    if args.check:
        if TARGET.read_text() != content:
            raise SystemExit("Image contract choices need regeneration")
    else:
        TARGET.write_text(content)


if __name__ == "__main__":
    main()
